import { useState } from 'react';
import './Phase3Semantic.css';

const QUESTIONS = [
    {
        id: 'semantic-q1',
        question: 'What information does a symbol table store?',
        options: [
            'Declared identifiers and their attributes',
            'Only the program output',
            'Machine instructions',
            'The source file name',
        ],
        answer: 'Declared identifiers and their attributes',
        explanation:
            'A symbol table records details such as a variable name, type, scope, and initialization state.',
    },
    {
        id: 'semantic-q2',
        question: 'When is an undeclared-variable error reported?',
        options: [
            'When a token appears on a new line',
            'When an identifier is used before it has been declared',
            'When an expression contains a constant',
            'When the parser sees a semicolon',
        ],
        answer: 'When an identifier is used before it has been declared',
        explanation:
            'Semantic analysis checks that identifiers referenced by expressions exist in the symbol table.',
    },
    {
        id: 'semantic-q3',
        question: 'What does type compatibility checking validate?',
        options: [
            'Whether tokens are in alphabetical order',
            'Whether the source code has a title',
            'Whether expression types are valid for their use',
            'Whether variables use short names',
        ],
        answer: 'Whether expression types are valid for their use',
        explanation:
            'The analyzer checks type rules for initializers, assignments, and operators.',
    },
    {
        id: 'semantic-q4',
        question: 'What does the initialized flag indicate?',
        options: [
            'Whether a value is known at compile time',
            'Whether a variable is a keyword',
            'Whether the program has been optimized',
            'Whether a variable has received a value',
        ],
        answer: 'Whether a variable has received a value',
        explanation:
            'Initialization status is distinct from whether the analyzer can determine a constant value.',
    },
    {
        id: 'semantic-q5',
        question: 'What does semantic analysis do with an undeclared identifier?',
        options: [
            'Adds the identifier to the symbol table',
            'Reports an undeclared-variable diagnostic',
            'Treats it as an integer literal',
            'Removes it from the expression',
        ],
        answer: 'Reports an undeclared-variable diagnostic',
        explanation:
            'Identifiers referenced by expressions must already have a matching declaration.',
    },
    {
        id: 'semantic-q6',
        question: 'What is a semantic error?',
        options: [
            'A spelling difference in an editor theme',
            'A token position in the source file',
            'A violation of meaning or type rules in a parsed program',
            'A machine instruction generated by optimization',
        ],
        answer: 'A violation of meaning or type rules in a parsed program',
        explanation:
            'Semantic analysis checks rules such as declarations, identifier use, and type compatibility.',
    },
];

function Phase3Semantic({
    activeTab,
    setActiveTab,
    result = null,
    compileError = '',
}) {
    const [currentQuestion, setCurrentQuestion] = useState(0);
    const [selectedAnswer, setSelectedAnswer] = useState(null);
    const [quizScore, setQuizScore] = useState(0);
    const [quizFinished, setQuizFinished] = useState(false);

    const semantic = result?.semantic ?? null;
    const symbolTable = semantic?.symbol_table ?? [];
    const semanticErrors = semantic?.errors ?? [];
    const pipelineErrors = Array.isArray(result?.errors) ? result.errors : [];
    const errors = semantic
        ? [
              ...semanticErrors,
              ...pipelineErrors.filter((error) => error.phase !== 'semantic'),
          ]
        : pipelineErrors;
    const hasResult = result !== null;
    const hasErrors = errors.length > 0 || Boolean(compileError);
    const parserFailed = pipelineErrors.some(
        (error) => error.phase === 'parser'
    );
    const lexerFailed = pipelineErrors.some((error) => error.phase === 'lexer');
    function startQuiz() {
        setCurrentQuestion(0);
        setSelectedAnswer(null);
        setQuizScore(0);
        setQuizFinished(false);
        setActiveTab('quiz');
    }

    function nextQuestion() {
        if (currentQuestion === QUESTIONS.length - 1) {
            setQuizFinished(true);
        } else {
            setCurrentQuestion((question) => question + 1);
            setSelectedAnswer(null);
        }
    }

    return (
        <section className="semantic-panel">
            <div className="semantic-header">
                <div>
                    <span className="semantic-eyebrow">
                        PHASE 03 / SEMANTIC ANALYSIS
                    </span>
                    <h2>Semantic Analyzer</h2>
                    <p>
                        Check variable declarations, type compatibility,
                        and identifier usage.
                    </p>
                </div>

                <span
                    className={`semantic-status ${
                        !hasResult && !compileError
                            ? 'status-idle'
                          : hasErrors || (hasResult && !semantic)
                              ? 'status-error'
                              : 'status-success'
                    }`}
                >
                    {!hasResult && !compileError
                        ? 'Awaiting results'
                        : compileError
                          ? 'Compiler unavailable'
                          : hasErrors
                          ? 'Errors detected'
                          : semantic
                            ? 'Analysis passed'
                            : 'Analysis unavailable'}
                </span>
            </div>

            <nav className="semantic-tabs" aria-label="Semantic analysis views">
                <button
                    type="button"
                    className={activeTab === 'output' ? 'active' : ''}
                    onClick={() => setActiveTab('output')}
                >
                    Output
                </button>

                <button
                    type="button"
                    className={activeTab === 'learn' ? 'active' : ''}
                    onClick={() => setActiveTab('learn')}
                >
                    Learn
                </button>

                <button
                    type="button"
                    className={activeTab === 'quiz' ? 'active' : ''}
                    onClick={startQuiz}
                >
                    Quiz
                </button>
            </nav>

            <div className="semantic-content">
                {activeTab === 'output' && (
                    <>
                        {semantic && (
                            <div className="semantic-summary">
                                <div className="semantic-stat">
                                    <span>Declared variables</span>
                                    <strong>{symbolTable.length}</strong>
                                </div>

                                <div className="semantic-stat">
                                    <span>Initialized</span>
                                    <strong>
                                        {
                                            symbolTable.filter(
                                                (symbol) => symbol.initialized
                                            ).length
                                        }
                                    </strong>
                                </div>

                                <div className="semantic-stat">
                                    <span>Semantic errors</span>
                                    <strong>{semanticErrors.length}</strong>
                                </div>
                            </div>
                        )}

                        {!hasResult && !compileError ? (
                            <div className="semantic-empty">
                                <span className="semantic-empty-icon">▦</span>
                                <h3>Your symbol table will appear here</h3>
                                <p>
                                    Compile a program to view the symbol table
                                    returned by semantic analysis.
                                </p>
                            </div>
                        ) : compileError ? (
                            <div className="semantic-empty" role="alert">
                                <h3>Semantic analysis could not run</h3>
                                <p>{compileError}</p>
                            </div>
                        ) : !semantic ? (
                            <div className="semantic-empty">
                                <h3>Semantic analysis could not run</h3>
                                <p>
                                    {parserFailed
                                        ? 'Parsing failed, so the compiler did not run semantic analysis.'
                                        : lexerFailed
                                          ? 'Lexical analysis failed, so the compiler did not run semantic analysis.'
                                          : 'The compiler did not return a semantic analysis result.'}
                                </p>
                            </div>
                        ) : symbolTable.length === 0 ? (
                            <div className="semantic-empty">
                                <h3>No variables declared</h3>
                                <p>
                                    The analyzer did not produce any symbol
                                    table entries for this program.
                                </p>
                            </div>
                        ) : (
                            <div className="semantic-table-wrapper">
                                <table className="semantic-table">
                                    <thead>
                                        <tr>
                                            <th>Name</th>
                                            <th>Type</th>
                                            <th>Scope</th>
                                            <th>Line</th>
                                            <th>Initialized</th>
                                            <th>Value</th>
                                        </tr>
                                    </thead>

                                    <tbody>
                                        {symbolTable.map((symbol, index) => (
                                            <tr
                                                key={`${symbol.name}-${index}`}
                                            >
                                                <td>
                                                    <code>{symbol.name}</code>
                                                </td>
                                                <td>
                                                    <span className="semantic-type">
                                                        {symbol.type}
                                                    </span>
                                                </td>
                                                <td>{symbol.scope ?? 'global'}</td>
                                                <td>
                                                    {symbol.line_declared ?? '—'}
                                                </td>
                                                <td>
                                                    <span
                                                        className={
                                                            symbol.initialized
                                                                ? 'semantic-bool yes'
                                                                : 'semantic-bool no'
                                                        }
                                                    >
                                                        {symbol.initialized
                                                            ? 'Yes'
                                                            : 'No'}
                                                    </span>
                                                </td>
                                                <td>
                                                    {symbol.value == null
                                                        ? '—'
                                                        : String(symbol.value)}
                                                </td>
                                            </tr>
                                        ))}
                                    </tbody>
                                </table>
                            </div>
                        )}
                    </>
                )}

                {activeTab === 'output' && (
                    <section className="semantic-diagnostics">
                        <h3>Diagnostics</h3>
                        {errors.length === 0 && !compileError ? (
                            <div className="semantic-empty">
                                <span className="semantic-empty-icon">✓</span>
                                <h3>
                                    {semantic
                                        ? 'No semantic errors'
                                        : hasResult
                                          ? 'No compiler diagnostics'
                                          : 'Diagnostics will appear here'}
                                </h3>
                                <p>
                                    {semantic
                                        ? 'The analyzer returned no semantic errors.'
                                        : 'Compile a program to see parser and semantic diagnostics.'}
                                </p>
                            </div>
                        ) : (
                            <>
                                {compileError && (
                                    <article className="semantic-error-card" role="alert">
                                        <div className="semantic-error-top">
                                            <strong>compiler_request_error</strong>
                                        </div>
                                        <p>{compileError}</p>
                                    </article>
                                )}
                                {errors.map((error, index) => (
                                <article
                                    className="semantic-error-card"
                                    key={`${error.phase}-${error.type}-${index}`}
                                >
                                    <div className="semantic-error-top">
                                        <strong>{error.type}</strong>
                                        <span>
                                            {error.line == null
                                                ? 'Location unavailable'
                                                : `Line ${error.line}${
                                                      error.column == null
                                                          ? ''
                                                          : `, Column ${error.column}`
                                                  }`}
                                        </span>
                                    </div>

                                    <p>{error.message}</p>
                                    <small>
                                        Phase: {error.phase ?? 'semantic'}
                                    </small>
                                </article>
                                ))}
                            </>
                        )}
                    </section>
                )}

                {activeTab === 'learn' && (
                    <div className="semantic-learning">
                        <article>
                            <span>01</span>
                            <div>
                                <h3>Symbol table</h3>
                                <p>
                                    Stores information about declared
                                    variables, including their names, types,
                                    scope, initialization status, and known
                                    values.
                                </p>
                            </div>
                        </article>

                        <article>
                            <span>02</span>
                            <div>
                                <h3>Undeclared variables</h3>
                                <p>
                                    A variable must be declared before it can
                                    be referenced in an expression.
                                </p>
                            </div>
                        </article>

                        <article>
                            <span>03</span>
                            <div>
                                <h3>Type compatibility</h3>
                                <p>
                                    The analyzer checks whether expressions
                                    are compatible with the declared variable
                                    type.
                                </p>
                            </div>
                        </article>

                        <article>
                            <span>04</span>
                            <div>
                                <h3>Initialization</h3>
                                <p>
                                    The symbol table tracks whether a variable
                                    has been initialized. This is separate
                                    from whether its value is known at compile
                                    time.
                                </p>
                            </div>
                        </article>
                    </div>
                )}

                {activeTab === 'quiz' && (
                    <section className="semantic-quiz">
                        {quizFinished ? (
                            <div className="quiz-result semantic-quiz-result">
                                <h2>Quiz Completed!</h2>
                                <p>
                                    Your score:{' '}
                                    <strong>
                                        {quizScore} / {QUESTIONS.length}
                                    </strong>
                                </p>
                                <button
                                    type="button"
                                    className="compile-button"
                                    onClick={startQuiz}
                                >
                                    Try Again
                                </button>
                            </div>
                        ) : (
                            <div className="quiz-content semantic-quiz-content">
                                <p className="quiz-progress">
                                    Question {currentQuestion + 1} of{' '}
                                    {QUESTIONS.length}
                                </p>
                                <h2>{QUESTIONS[currentQuestion].question}</h2>
                                <div className="quiz-options">
                                    {QUESTIONS[currentQuestion].options.map(
                                        (option, index) => (
                                            <button
                                                type="button"
                                                key={option}
                                                className={`quiz-option ${
                                                    selectedAnswer === index
                                                        ? 'selected'
                                                        : ''
                                                } ${
                                                    selectedAnswer === index &&
                                                    option ===
                                                        QUESTIONS[
                                                            currentQuestion
                                                        ].answer
                                                        ? 'correct'
                                                        : selectedAnswer ===
                                                              index
                                                          ? 'incorrect'
                                                          : ''
                                                }`}
                                                disabled={
                                                    selectedAnswer !== null
                                                }
                                                onClick={() => {
                                                    setSelectedAnswer(index);
                                                    if (
                                                        option ===
                                                        QUESTIONS[
                                                            currentQuestion
                                                        ].answer
                                                    ) {
                                                        setQuizScore(
                                                            (score) => score + 1
                                                        );
                                                    }
                                                }}
                                            >
                                                {String.fromCharCode(65 + index)}.{' '}
                                                {option}
                                            </button>
                                        )
                                    )}
                                </div>
                                {selectedAnswer !== null && (
                                    <div
                                        className={`quiz-feedback ${
                                            QUESTIONS[currentQuestion]
                                                .options[selectedAnswer] ===
                                            QUESTIONS[currentQuestion].answer
                                                ? 'correct'
                                                : 'incorrect'
                                        }`}
                                    >
                                        <p>
                                            <strong>
                                                {QUESTIONS[currentQuestion]
                                                    .options[selectedAnswer] ===
                                                QUESTIONS[currentQuestion].answer
                                                    ? 'Correct!'
                                                    : 'Not quite!'}
                                            </strong>
                                        </p>
                                        <p>
                                            {
                                                QUESTIONS[currentQuestion]
                                                    .explanation
                                            }
                                        </p>
                                        <button
                                            type="button"
                                            className="compile-button"
                                            onClick={nextQuestion}
                                        >
                                            {currentQuestion ===
                                            QUESTIONS.length - 1
                                                ? 'View Score'
                                                : 'Next Question'}
                                        </button>
                                    </div>
                                )}
                            </div>
                        )}
                    </section>
                )}
            </div>
        </section>
    );
}

export default Phase3Semantic;
